type Messages map[string]string

func (m Messages) T(key string) string {
	if m == nil {
		return key
	}
	if v, ok := m[key]; ok {
		return v
	}
	return key
}

func (m Messages) Tf(key string, args ...any) string {
	template := m.T(key)
	if len(args) == 0 {
		return template
	}
	return fmt.Sprintf(template, args...)
}

func DefaultMessages() Messages {
	return Messages(defaultMessagesMap)
}

func MessagesForLang(lang string) Messages {
	base := DefaultMessages()
	if lang == "" {
		return base
	}
	if override, ok := langMessagesMap[normalizeLang(lang)]; ok {
		merged := make(Messages, len(base)+len(override))
		for k, v := range base {
			merged[k] = v
		}
		for k, v := range override {
			merged[k] = v
		}
		return merged
	}
	return base
}

func DetectLangFromRequest(r *http.Request) string {
	if r == nil {
		return ""
	}
	accept := r.Header.Get("Accept-Language")
	if accept == "" {
		return ""
	}
	tags, _, err := language.ParseAcceptLanguage(accept)
	if err != nil || len(tags) == 0 {
		return ""
	}
	matcher := language.NewMatcher(supportedTags)
	tag, _, _ := matcher.Match(tags...)
	base, _ := tag.Base()
	return base.String()
}

func normalizeLang(lang string) string {
	return strings.ToLower(strings.TrimSpace(lang))
}

